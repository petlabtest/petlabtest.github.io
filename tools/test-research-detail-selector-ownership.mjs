import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const research = path.join(root, 'Research');
const sharedCss = fs.readFileSync(path.join(root, 'assets/css/research/research-detail-shared.css'), 'utf8');
const runtimeClassOwners = new Map([
  ['last-word', 'assets/js/root/r006.js'],
]);
const pages = fs.readdirSync(research)
  .filter(file => /^Research-(?:.+-Page\d+)-(?:cn|en)\.html$/.test(file))
  .sort()
  .map(file => ({ file, html: fs.readFileSync(path.join(research, file), 'utf8') }))
  .filter(({ html }) => html.includes('research-detail-shared.css'));

assert.equal(pages.length, 44, 'shared Research detail stylesheet consumer count changed');
const languages = new Map();
for (const { file, html } of pages) {
  const language = /<html\b[^>]*\blang=["']([^"']+)/i.exec(html)?.[1];
  assert.ok(language === 'zh-CN' || language === 'en', `${file}: shared Research detail language changed`);
  assert.ok(/\bclass=["'][^"']*\bpage-node-type-rdgroup\b/i.test(html), `${file}: shared container class missing`);
  languages.set(language, (languages.get(language) || 0) + 1);
}
assert.deepEqual(Object.fromEntries(languages), { en: 22, 'zh-CN': 22 }, 'shared Research detail language coverage changed');
const domClasses = new Set(pages.flatMap(({ html }) =>
  [...html.matchAll(/\bclass=["']([^"']+)["']/g)].flatMap(([, value]) => value.split(/\s+/))));
const css = sharedCss.replace(/\/\*[\s\S]*?\*\//g, '');
assert.equal((css.match(/html\[lang\] \.page-node-type-rdgroup \.paragraph--type-p-fullwidth\.background--grey\.slope--pos\.js-animate/g) || []).length, 1, 'shared desktop slope offset should use one language-neutral selector');
assert.doesNotMatch(css, /html\[lang=["'](?:en|zh-CN)["']\] \.page-node-type-rdgroup \.paragraph--type-p-fullwidth\.background--grey\.slope--pos\.js-animate/, 'remove duplicate language-specific slope selectors');
const selectors = new Set([...css.matchAll(/\.([a-zA-Z_][\w-]*)/g)].map(([, className]) => className));
const runtimeClasses = [];
for (const className of selectors) {
  if (domClasses.has(className)) continue;
  const ownerPath = runtimeClassOwners.get(className);
  assert.ok(ownerPath, `.${className} has neither a static DOM owner nor a declared runtime owner`);
  const owner = fs.readFileSync(path.join(root, ownerPath), 'utf8');
  assert(owner.includes(`class="${className}"`), `.${className} runtime owner no longer generates the class`);
  runtimeClasses.push(className);
}

assert.deepEqual([...runtimeClasses], ['last-word'], 'review changes to the dynamic-class ownership contract');
process.stdout.write(`PASS: ${pages.length} Research detail pages own ${selectors.size - runtimeClasses.length} shared CSS classes in HTML; ${runtimeClasses.join(', ')} is generated by its documented runtime script.\n`);
